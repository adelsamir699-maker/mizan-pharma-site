-- ============================================================================
-- ترحيل ٧٧ — «ميزان فارما»: معرّفات الدفعات المصروفة داخل سجل الصرف
-- ----------------------------------------------------------------------------
-- عشان حذف الفاتورة/المرتجع يرجّع الكمية **لنفس الدفعة** (مش لمخزن الصنف بس)،
-- محتاجين نحفظ خريطة: batch id + الكمية + رقم الدفعة + تاريخ الانتهاء + المستودع.
-- العمود jsonb افتراضه [] فالصفوف القديمة تفضل شغالة (ترجيع تقريبي من ملخص الدفعات).
-- الترحيل إضافة بس (idempotent)، وما يلمسش الدخول/الباسورد/الاشتراكات/الدعوات.
-- ============================================================================

alter table public.pharma_dispenses
  add column if not exists batch_refs jsonb not null default '[]'::jsonb;

comment on column public.pharma_dispenses.batch_refs is
  'معرّفات الدفعات اللي اتخصمت من الصرف (id/qty/no/expiry/warehouse/productId) — تُستخدم عند الحذف/المرتجع';

notify pgrst, 'reload schema';
